/** Подход, которого ещё не было у иконки. Если все исчерпаны — начинает круг заново. */
export function pickDirection(usedIds = []) {
  const used = new Set(usedIds)
  const fresh = directions.filter((direction) => !used.has(direction.id))
  const pool = fresh.length > 0 ? fresh : directions
  const direction = pool[Math.floor(Math.random() * pool.length)]

  return { direction, restarted: fresh.length === 0 }
}
